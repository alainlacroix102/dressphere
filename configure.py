#!/usr/bin/env python3
"""Generate build.ninja for the FFX-2 (SLUS-20672) decompilation.

Usage:
    python3 configure.py            # re-run splat, then write build.ninja
    python3 configure.py --no-split # only write build.ninja
    ninja                           # build + checksum the rebuilt binary
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
YAML = "ffx2.yaml"
BASENAME = "SLUS_206.72"
LD_SCRIPT = f"{BASENAME}.ld"
TARGET_ROM = f"iso/{BASENAME}.rom"
# SHA1 of the objcopy'd binary of the retail ELF (iso/files/SLUS_206.72,
# whose own sha1 is 1cde3cd6d36e0a6ff6ac3d10b2ff6b4d74a6073e).
ROM_SHA1 = "183475f01ab99b5760dd7160614f4da6ec2ff87f"

CROSS = "mips-linux-gnu-"
# Original compiler (see docs/COMPILER.md). Linux build from decompme/compilers.
# Original compiler: Sony ee-gcc 2.9-ee-991111, -O2 -G0 (see docs/COMPILER.md).
# tools/eecc.py runs cpp -> original cc1 -> modern gas.
COMPILER = "ee-gcc2.9-991111"
CFLAGS = "-O2 -G0"
ASFLAGS = "-EL -march=r5900 -mabi=32 -G0 -no-pad-sections -Iinclude"


# Section start alignments used by the retail link (from the ELF section
# headers). splat's generated script doesn't know these, so patch them in.
SECTION_ALIGN = {"cod_SBSS_START": 128, "cod_BSS_START": 256}


def run_splat() -> None:
    subprocess.check_call([sys.executable, "-m", "splat", "split", YAML], cwd=ROOT)


def patch_ld_script() -> None:
    path = ROOT / LD_SCRIPT
    text = path.read_text()
    for sym, align in SECTION_ALIGN.items():
        line = f"{sym} = .;"
        fixed = f". = ALIGN({align});\n        {line}"
        if fixed not in text:
            text = text.replace(line, fixed)
    path.write_text(text)


def objects_from_ld() -> list[str]:
    text = (ROOT / LD_SCRIPT).read_text()
    seen: dict[str, None] = {}
    for m in re.finditer(r"(build/\S+?\.o)\(", text):
        seen.setdefault(m.group(1), None)
    return list(seen)


def source_for(obj: str) -> Path:
    stem = obj[len("build/"):-len(".o")]
    for cand in (stem, stem.removesuffix(".s"), stem.removesuffix(".c")):
        for ext in ("", ".s", ".c"):
            p = ROOT / (cand + ext)
            if p.is_file() and p.suffix in (".s", ".c"):
                return p.relative_to(ROOT)
    raise SystemExit(f"configure.py: no source found for {obj}")


def write_ninja(objs: list[str]) -> None:
    out: list[str] = []
    w = out.append
    w("# Generated by configure.py -- do not edit\n")
    w(f"cross = {CROSS}\n")
    w(f"compiler = {COMPILER}\n")
    w(f"cflags = {CFLAGS}\n")
    w(f"asflags = {ASFLAGS}\n\n")

    w("rule as\n  command = ${cross}as $asflags -o $out $in && ${cross}objcopy --set-section-alignment .text=8 $out\n  description = AS $in\n\n")
    # C: original compiler emits asm, which modern GNU as assembles for r5900.
    w(
        "rule cc\n"
        "  command = python3 tools/eecc.py -c $compiler -f '$cflags' -o $out $in\n"
        "  description = CC $in\n\n"
    )
    w(
        "rule ld\n"
        "  command = ${cross}ld -EL -T undefined_syms_auto.txt -T undefined_funcs_auto.txt "
        "-T linker_script_extra.ld -T $ldscript -Map build/" + BASENAME + ".map "
        "--no-check-sections -o $out\n"
        "  description = LD $out\n\n"
    )
    w("rule objcopy\n  command = ${cross}objcopy -O binary --gap-fill=0x00 $in $out\n  description = OBJCOPY $out\n\n")
    w(
        "rule check\n"
        "  command = echo '" + ROM_SHA1 + "  $in' | sha1sum -c --quiet - && echo 'OK: matches retail' > $out "
        "|| (echo 'MISMATCH: rebuilt binary differs from retail'; exit 1)\n"
        "  description = CHECK $in\n\n"
    )

    for obj in objs:
        src = source_for(obj)
        rule = "as" if src.suffix == ".s" else "cc"
        dep = " | tools/eecc.py" if rule == "cc" else ""
        w(f"build {obj}: {rule} {src}{dep}\n")

    elf = f"build/{BASENAME}.elf"
    w(f"\nbuild {elf}: ld {' '.join(objs)} | {LD_SCRIPT}\n  ldscript = {LD_SCRIPT}\n")
    w(f"build build/{BASENAME}.rom: objcopy {elf}\n")
    w(f"build build/{BASENAME}.ok: check build/{BASENAME}.rom\n")
    w(f"default build/{BASENAME}.ok\n")
    (ROOT / "build.ninja").write_text("".join(out))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-split", action="store_true", help="skip running splat")
    args = ap.parse_args()
    if not args.no_split:
        run_splat()
    patch_ld_script()
    write_ninja(objects_from_ld())


if __name__ == "__main__":
    main()
